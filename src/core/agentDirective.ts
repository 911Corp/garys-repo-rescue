import { fmtDate } from './dates'
import { modernizationIdeas } from './rescuePlan'
import type { Project } from './types'

/**
 * Agent directive: an AGENTS.md / CLAUDE.md file to drop at the root of a fresh clone,
 * so a coding agent (Claude Code, Codex, Cursor, Aider…) starts a rescue with the right guardrails.
 *
 * Same rules as the Rescue Plan: nothing invented. Facts come from the catalog, every
 * unknown becomes a task "find out", and suggestions are labelled as hypotheses.
 */
export function agentDirectiveMarkdown(p: Project, opts: { generatedAt: string; appUrl?: string }): string {
  const a = p.a
  const q = p.quality
  const L: string[] = []
  const blockedByLicense = a.licenseStatus === 'No Explicit License' || a.licenseStatus === 'Unknown'
  const successor = p.forkIntel.possibleSuccessor ?? p.forkIntel.successorHints[0]?.repo ?? null

  L.push(`# AGENTS.md: rescue of ${p.fullName}`, '')
  L.push(`<!-- Generated by Gary's Repo Rescue on ${fmtDate(opts.generatedAt)}. Save as AGENTS.md (or CLAUDE.md) at the root of your clone. -->`, '')
  L.push('You are a coding agent helping a developer revive an existing open source project.', 'Read this whole file before acting. It overrides your habits, not the developer\'s instructions.', '')

  L.push('## Known facts (from public metadata, not verified by running anything)', '')
  L.push(`- Upstream: ${p.url}`)
  L.push(`- Description: ${p.description ?? '(none)'}`)
  L.push(`- Primary language: ${p.language ?? 'not reported'}${q.manifests.length ? ` · root manifests: ${q.manifests.join(', ')}` : ''}`)
  L.push(`- Last push: ${fmtDate(p.pushedAt)} · status: ${a.maintenance}${p.archived ? ' (archived upstream)' : ''}`)
  L.push(`- License: ${p.license.spdx ?? 'none detected'} → ${a.licenseStatus}`)
  L.push(`- Tests detected: ${q.tests == null ? 'unknown' : q.tests ? 'yes' : 'no'} · CI detected: ${q.ci == null ? 'unknown' : q.ci ? q.ciProviders.join(', ') : 'no'}`)
  if (a.legacyTech.length) L.push(`- Legacy markers: ${a.legacyTech.join(', ')}`)
  if (successor) L.push(`- Possible successor or active fork: https://github.com/${successor}`)
  L.push('')

  L.push('## Non-negotiable rules', '')
  L.push('1. Never invent facts. If you don\'t know a command, a version or a behaviour, find it in the code, the README or the manifests, and say where you found it.')
  L.push('2. Do not run install scripts, build steps or binaries from this repository outside an isolated environment (container, VM or disposable sandbox).')
  L.push('3. Keep every original copyright and license notice. Do not relicense.')
  L.push('4. Work in small, reviewable commits on a branch. One concern per commit.')
  L.push('5. Do not upgrade dependencies before the project builds with its original versions (Phase 1).')
  L.push('6. Never commit secrets, tokens or credentials, including ones found in the history.')
  L.push('7. Do not push, publish, release or open pull requests upstream without the developer\'s explicit approval.')
  L.push('')

  L.push('## Stop and ask the developer if', '')
  if (blockedByLicense) L.push('- **Now:** the license is not clear. Do nothing beyond reading code until the developer confirms they have the right to reuse it.')
  else L.push('- you find a license file, header or dependency that contradicts the declared license.')
  if (successor) L.push(`- **Before Phase 1:** compare with ${successor}. If it already does the job, recommend contributing there instead of forking.`)
  L.push('- the build needs a paid service, a private registry or credentials you don\'t have.')
  L.push('- you find suspicious code (obfuscated scripts, unexpected network calls at install time, crypto miners).')
  L.push('- a fix requires a breaking change to the public API, file formats or data.')
  L.push('')

  L.push('## Phases (do them in order)', '')
  L.push('### Phase 0: Reconnaissance (read only)', '')
  L.push('- Map the structure: entry points, main modules, build files, config, tests.')
  L.push(`- Find the real install/build/run commands${q.installInstructions ? ' (the README has an install section: start there)' : ' (no install section detected in the README: look in the manifests and CI files)'}.`)
  L.push('- Find the runtime and toolchain versions the project expected at its last commit.')
  L.push('- **Done when:** you have written `RESCUE_NOTES.md` with the structure, the commands (with their source), the expected versions and open questions.', '')

  L.push('### Phase 1: Make it build as-is', '')
  L.push('- Inside a sandbox, install the original toolchain versions and build without changing dependencies.')
  L.push('- Record every error and the minimal fix. Pin versions if they were floating.')
  L.push(`- **Done when:** the project builds (and ${q.tests ? 'the existing tests run' : 'the main feature starts'}) from a clean clone with documented steps.`, '')

  L.push('### Phase 2: Safety net', '')
  L.push(q.tests ? '- Get the existing test suite green; mark and explain any test you had to skip.' : '- No tests were detected: add smoke tests for the main feature before changing anything else.')
  if (!q.ci) L.push('- Add a CI workflow that installs, builds and runs the tests on every push.')
  L.push('- **Done when:** a red/green signal exists and runs automatically.', '')

  L.push('### Phase 3: Upgrade', '')
  L.push('- Upgrade the runtime, then dependencies, one major version at a time, with tests after each step.')
  L.push('- Run the ecosystem\'s audit tool and fix known vulnerabilities; list what remains.')
  L.push('- **Done when:** current supported versions, audit clean or documented, tests green.', '')

  L.push('### Phase 4: Modernize (hypotheses to validate with the developer)', '')
  for (const s of modernizationIdeas(p)) L.push(`- ${s}`)
  L.push('')

  L.push('## Report format', '')
  L.push('After each phase, report in this shape:', '')
  L.push('```')
  L.push('Phase: <n>')
  L.push('Done: <what changed, with commit hashes>')
  L.push('Verified: <commands run and their result>')
  L.push('Not verified / assumptions: <list>')
  L.push('Blockers / questions: <list>')
  L.push('Next: <proposed next step>')
  L.push('```', '')

  if (opts.appUrl) L.push(`_Source: ${opts.appUrl}_`, '')
  L.push('_Built by Gary. Rescued with Jarvis._')
  return L.join('\n')
}
