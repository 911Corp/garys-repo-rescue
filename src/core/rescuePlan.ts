import { fmtDate, humanAge } from './dates'
import type { Project } from './types'

/**
 * Deterministic Rescue Plan (Markdown), meant to be handed to a human or a coding agent.
 * Rules: never invent commands, vulnerabilities or problems. When a fact is missing,
 * write the check to perform instead.
 */

const MANIFEST_HINTS: Record<string, string> = {
  'package.json': 'Node.js project: read the `scripts` section of package.json to find the real install/build/run commands.',
  'bower.json': 'Bower manifest found: Bower is deprecated, plan a migration to npm.',
  'Gruntfile.js': 'Grunt build file found: identify the tasks before replacing with a modern bundler.',
  'gulpfile.js': 'Gulp build file found: list the tasks before replacing them.',
  'requirements.txt': 'Python dependencies in requirements.txt: check the Python version they assume.',
  'setup.py': 'setup.py found: check the declared Python version and entry points.',
  'pyproject.toml': 'pyproject.toml found: read the build backend and declared Python version.',
  'Pipfile': 'Pipfile found: Pipenv-based environment.',
  'Cargo.toml': 'Rust crate: read Cargo.toml for the edition and the binary targets.',
  'go.mod': 'Go module: check the Go version declared in go.mod.',
  'Gemfile': 'Ruby project: check the Ruby version and Bundler setup.',
  'composer.json': 'PHP project: check the PHP version constraint in composer.json.',
  'pom.xml': 'Maven project: check the Java version and plugins in pom.xml.',
  'build.gradle': 'Gradle project: check the Gradle and Java versions.',
  'build.gradle.kts': 'Gradle (Kotlin DSL) project: check the Gradle and JVM versions.',
  'CMakeLists.txt': 'CMake project: check the minimum CMake version and required system libraries.',
  'Makefile': 'Makefile found: read its targets before running anything.',
  'Dockerfile': 'Dockerfile found: the base image may be outdated, check it before building.',
  'docker-compose.yml': 'docker-compose.yml found: list the services and their images.',
  'docker-compose.yaml': 'docker-compose.yaml found: list the services and their images.',
  'pubspec.yaml': 'Flutter/Dart project: check the SDK constraint in pubspec.yaml.',
  'Package.swift': 'Swift package: check the Swift tools version.',
  'mix.exs': 'Elixir project: check Elixir/OTP versions in mix.exs.',
}

export function rescuePlanMarkdown(p: Project, opts: { generatedAt: string; appUrl?: string }): string {
  const a = p.a
  const q = p.quality
  const L: string[] = []
  const na = (k: string) => p.meta.unavailable.includes(k)
  const yesNo = (v: boolean | null, missingKey?: string) => (v == null || (missingKey && na(missingKey)) ? 'not checked' : v ? 'yes' : 'not detected')

  L.push(`# Rescue Plan: ${p.fullName}`, '')
  L.push(`> Generated by Gary's Repo Rescue on ${fmtDate(opts.generatedAt)}. Facts come from public metadata (${p.meta.sources.join(', ')}), last verified ${fmtDate(p.meta.verifiedAt)}. Nothing here was run or tested. Suggestions are marked as such.`, '')

  L.push('## 1. Summary', '')
  L.push(`- Repository: ${p.url}`)
  L.push(`- Description: ${p.description ?? '(none provided by the owner)'}`)
  if (p.homepage) L.push(`- Homepage / demo: ${p.homepage}`)
  L.push(`- Created: ${fmtDate(p.createdAt)} · Last push: ${fmtDate(p.pushedAt)}${p.lastCommitAt ? ` · Last commit: ${fmtDate(p.lastCommitAt)}` : ''}`)
  L.push(`- Stars: ${p.stars} · Forks: ${p.forks}${p.contributors != null ? ` · ${p.contributorsBasis === 'commit-authors' ? 'Commit authors' : 'Contributors'}: ${p.contributors}` : ''}`)
  L.push(`- Maintenance status: **${a.maintenance}** (${a.maintenanceReason})`)
  L.push(`- Rescue Score: **${a.rescue.score}/100** (${Math.round(a.rescue.coverage * 100)}% of criteria computable)`)
  L.push(`- Revival difficulty: **${a.difficulty}**`)
  L.push(`- Data confidence: **${a.confidence.level}** (${a.confidence.score}/100)`, '')

  L.push('## 2. License and precautions', '')
  L.push(`- Declared license: ${p.license.spdx ?? 'none detected'}${p.license.name ? ` (${p.license.name})` : ''}`)
  L.push(`- Status: **${a.licenseStatus}**. ${a.licenseNote}`)
  if (p.license.url) L.push(`- License file: ${p.license.url}`)
  L.push('- Before reusing: keep the copyright and license notices, and check the license of each dependency.')
  if (a.licenseStatus === 'No Explicit License' || a.licenseStatus === 'Unknown') L.push('- **Stop here until the license is clarified.** Contact the author or open an issue asking for a license.')
  L.push('')

  L.push('## 3. Technologies', '')
  L.push(`- Primary language: ${p.language ?? 'not reported'}`)
  if (p.languages?.length) L.push(`- Languages by size: ${p.languages.map((l) => `${l.name} ${Math.round(l.share * 100)}%`).join(', ')}`)
  if (p.topics.length) L.push(`- Topics: ${p.topics.join(', ')}`)
  if (q.manifests.length) L.push(`- Build / dependency manifests at root: ${q.manifests.join(', ')}`)
  if (a.legacyTech.length) L.push(`- Legacy technology markers: ${a.legacyTech.join(', ')}`)
  L.push('')

  L.push('## 4. Available documentation', '')
  L.push(`- README: ${yesNo(q.readme)}${q.readmeBytes ? ` (${Math.round(q.readmeBytes / 1024)} KB)` : ''}`)
  L.push(`- Install / getting-started section in README: ${yesNo(q.installInstructions, 'readme')}`)
  L.push(`- Docs folder: ${yesNo(q.docs, 'quality.docs')}`)
  L.push(`- Examples / demo folder: ${yesNo(q.examples, 'quality.examples')}`)
  L.push(`- CONTRIBUTING: ${yesNo(q.contributing)} · CHANGELOG: ${yesNo(q.changelog)}`)
  L.push(`- Tests: ${yesNo(q.tests)} · CI: ${q.ci ? q.ciProviders.join(', ') : yesNo(q.ci)}`, '')

  L.push('## 5. Apparent maintenance state', '')
  L.push(`- Last activity: ${humanAge(a.monthsSinceActivity)}`)
  if (p.commitsTotal != null) L.push(`- Commits on default branch: ${p.commitsTotal}${p.commits12m != null ? ` (${p.commits12m} in the last 12 months)` : ''}`)
  if (p.latestRelease) L.push(`- Latest release: ${p.latestRelease.tag} (${fmtDate(p.latestRelease.publishedAt)})`)
  else if (!na('latestRelease')) L.push('- No GitHub release published.')
  if (p.openIssues != null) L.push(`- Open issues: ${p.openIssues}${p.openPrs != null ? ` · Open PRs: ${p.openPrs}` : ''}`)
  else L.push(`- Open issues + PRs: ${p.openIssuesAndPrs}`)
  if (p.forkIntel.successorHints.length) for (const h of p.forkIntel.successorHints) L.push(`- README points to a possible new home: https://github.com/${h.repo}`)
  if (p.forkIntel.possibleSuccessor) L.push(`- A fork looks actively maintained: https://github.com/${p.forkIntel.possibleSuccessor}`)
  if (!p.forkIntel.checked) L.push(`- Forks were not inspected. Check ${p.url}/forks before starting your own.`)
  L.push('')

  L.push('## 6. Dependencies to examine', '')
  if (q.manifests.length) for (const m of q.manifests) L.push(`- ${MANIFEST_HINTS[m] ?? `${m}: read it to list dependencies and their versions.`}`)
  else L.push('- No root manifest detected (or not checked). Look for build files in sub-folders and in the README.')
  L.push('- Run your ecosystem\'s audit tool after installing, and note every deprecated or vulnerable package. (Not run by Repo Rescue.)', '')

  L.push('## 7. Local launch: steps to figure out', '')
  L.push('Repo Rescue does not invent install commands. Find the real ones in this order:', '')
  L.push(`1. Clone: \`git clone ${p.url}.git\``)
  L.push(`2. Read the README${q.installInstructions ? ' (it has an install / getting-started section)' : ''}${q.manifests.length ? ` and the manifests: ${q.manifests.join(', ')}` : ''}.`)
  L.push('3. Identify the runtime version expected at the time of the last commit, and install that version first.')
  L.push('4. Install dependencies, then try the documented build and run commands. Write down every error.')
  L.push('5. Work in a sandbox or container: this code has not been reviewed by Repo Rescue.', '')

  L.push('## 8. Initial checks', '')
  L.push('- [ ] License read and compatible with your plans')
  L.push('- [ ] No active successor or fork already doing the job')
  L.push('- [ ] Project builds with its original toolchain')
  L.push(`- [ ] ${q.tests ? 'Existing tests run and pass' : 'Write a smoke test of the main feature (no tests detected)'}`)
  L.push('- [ ] Dependencies audited for known vulnerabilities')
  L.push('- [ ] Open issues skimmed for known bugs and feature requests', '')

  L.push('## 9. Modernization suggestions (hypotheses)', '')
  for (const s of modernizationIdeas(p)) L.push(`- ${s}`)
  L.push('')

  L.push('## 10. Technical priorities (suggested order)', '')
  L.push('1. Make it build and run as-is, pinned to its original versions.')
  L.push(`2. Add a safety net: ${q.tests ? 'get the existing tests green' : 'a few smoke tests'}${q.ci ? '' : ' and a CI workflow'}.`)
  L.push('3. Upgrade the runtime and dependencies step by step, one major version at a time.')
  L.push(`4. ${a.legacyTech.length ? `Replace legacy pieces (${a.legacyTech.join(', ')}).` : 'Refresh the developer experience (lint, format, scripts).'}`)
  L.push('5. Only then: new features, UI refresh, new deployment target.', '')

  L.push('## 11. Identified risks', '')
  if (a.cautions.length) for (const c of a.cautions) L.push(`- ${c}`)
  else L.push('- No specific risk flagged from metadata. That is not proof of absence.')
  L.push('')

  L.push('## 12. First roadmap', '')
  L.push('- **Week 1:** license check, build as-is, list of breaking errors, decision: contribute upstream or fork.')
  L.push('- **Week 2:** tests + CI, dependency upgrades, README rewritten with real install steps.')
  L.push('- **Week 3+:** modernization items above, first release under a clear version.', '')

  L.push('## Notes for a coding agent', '')
  L.push('- Treat every statement in sections 9 to 12 as a suggestion to verify, not a fact.')
  L.push('- Do not run install scripts from this repository outside an isolated environment.')
  L.push('- Preserve the original license and authorship notices.')
  L.push('- If the upstream project is still reachable, prefer opening pull requests there.')
  if (opts.appUrl) L.push('', `_Source: ${opts.appUrl}_`)
  L.push('', '_Built by Gary. Rescued with Jarvis._')
  return L.join('\n')
}

/** Suggestions derived from facts. Always phrased as hypotheses. */
export function modernizationIdeas(p: Project): string[] {
  const out: string[] = []
  const t = p.a.legacyTech
  if (t.includes('CoffeeScript')) out.push('Convert CoffeeScript to TypeScript (decaffeinate can do a first pass).')
  if (t.includes('AngularJS 1.x')) out.push('AngularJS is end-of-life: consider a rewrite of the UI layer in a current framework, keeping the business logic.')
  if (t.includes('Bower') || t.includes('Grunt') || t.includes('Gulp')) out.push('Replace the Bower/Grunt/Gulp toolchain with npm + a modern bundler such as Vite.')
  if (t.includes('jQuery-era frontend')) out.push('Check which jQuery features are used; many can become plain DOM APIs.')
  if (t.includes('Python 2')) out.push('Port to Python 3 (start with automated tools, then fix by hand).')
  if (t.includes('Travis CI config')) out.push('Move the Travis CI configuration to GitHub Actions.')
  if (t.includes('ActionScript / Flash')) out.push('Flash is gone: the logic may be portable to HTML5 Canvas or WebGL.')
  if (t.includes('Objective-C')) out.push('Evaluate a progressive move to Swift for new code.')
  if (p.language === 'JavaScript') out.push('Add TypeScript progressively (JSDoc types first) to make refactoring safer.')
  if (p.quality.dockerfile === false && /self|server|host|web|api|dashboard/i.test(`${p.topics.join(' ')} ${p.description ?? ''}`)) out.push('Add a Dockerfile / compose file for one-command self-hosting.')
  if (p.quality.tests === false) out.push('Write tests for the core feature before changing anything (a good job for a coding agent).')
  if (p.quality.ci === false) out.push('Add a CI workflow that builds and runs the tests on every push.')
  if (p.quality.screenshots === false) out.push('Add screenshots or a short GIF to the README so people get it in five seconds.')
  if (!p.homepage) out.push('Publish a live demo (static hosting if it is a frontend).')
  if (p.a.collections.includes('local-first')) out.push('Check whether the sync layer could use a current CRDT library.')
  if (out.length === 0) out.push('Refresh dependencies and documentation; no specific legacy marker was detected.')
  return out
}
